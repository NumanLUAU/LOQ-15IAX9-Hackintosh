def build_config(name, prof, smbios):
    p = plistlib.load(open(os.path.join(OC, "Docs", "Sample.plist"), "rb"))
    for k in [k for k in p if k.startswith("#")]:
        del p[k]

    # ACPI
    acpi = ["SSDT-EC-USBX.aml", "SSDT-PLUG.aml", "SSDT-RTCAWAC.aml", "SSDT-GPRW.aml", "SSDT-XOSI.aml"]
    if prof["pnlf"]:
        acpi.append("SSDT-PNLF.aml")
    p["ACPI"]["Add"] = [acpi_add(a) for a in acpi]
    p["ACPI"]["Delete"] = []
    base_patch = p["ACPI"]["Patch"][0]
    def patch(comment, find, repl):
        d = dict(base_patch); d.update(Comment=comment, Enabled=True, Find=hexb(find), Replace=hexb(repl), Count=0,
                                         Mask=b"", ReplaceMask=b"", OemTableId=b"", TableSignature=b"")
        return d
    p["ACPI"]["Patch"] = [
        patch("_OSI to XOSI (pairs with SSDT-XOSI.aml)", "5F4F5349", "584F5349"),
        patch("GPRW,2 to XPRW (pairs with SSDT-GPRW.aml)", "4750525702", "5850525702"),
        # macOS's ACPICA (2016) aborts the whole DSDT load at Scope(_SB.PC00.XHCI.RHUB.HS06): HS06 only exists when PU2C>=6 at run time.
        # Turn that Scope (10 42 18 + 22-byte path, followed by Method _UPC) into If (One) + 21 Noop, same length - exactly what the
        # reference EFI's custom DSDT does, but as a runtime patch so firmware NVS addresses stay live.
        dict(patch("DSDT: Scope(...XHCI.RHUB.HS06) -> If (One)+Noops (fixes 'DSDT table load failed')",
                   "10 42 18 2F05 5F53425F 50433030 58484349 52485542 48533036 140C5F555043".replace(" ", ""),
                   "A0 42 18 01" .replace(" ", "") + "A3" * 21 + "140C5F555043"), TableSignature=hexb("44534454")),
    ]
    p["ACPI"]["Quirks"].update(ResetLogoStatus=True)

    # Booter
    q = p["Booter"]["Quirks"]
    q.update(AllowRelocationBlock=True, AvoidRuntimeDefrag=True, DevirtualiseMmio=True, EnableSafeModeSlide=True,
             EnableWriteUnprotector=False, FixupAppleEfiImages=True, ProtectUefiServices=True, ProvideCustomSlide=True,
             RebuildAppleMemoryMap=True, SetupVirtualMap=True, SyncRuntimePermissions=True, SignalAppleOS=False,
             ResizeAppleGpuBars=prof["resize_apple"])

    # DevirtualiseMmio removes the kernel mapping of the 0xFF000000 firmware flash/NVRAM region; the kernel
    # then page-faults on it (observed panic: CR2 0xFF04504C, ~1 s after EXITBS). Whitelist it (same as the reference EFI).
    p["Booter"]["MmioWhitelist"] = [{"Address": 0xFF000000, "Comment": "Firmware flash/NVRAM region; fixes page fault at 0xFF04504C", "Enabled": True}]
    p["UEFI"]["Quirks"]["EnableVectorAcceleration"] = False

    # DeviceProperties
    dp = {
        "PciRoot(0x0)/Pci(0x1f,0x3)": {"layout-id": hexb("63000000")},
        "PciRoot(0x0)/Pci(0x15,0x0)": {"force-polling": hexb("01000000")},
    }
    p["DeviceProperties"]["Add"] = dp
    p["DeviceProperties"]["Delete"] = {}

    # Kernel
    net = [k for k in NET_KEXTS if not (prof.get("minimal") and k in ("AirportItlwm", "HoRNDIS", "USBToolBox", "UTBMap"))]
    keys = BASE_KEXTS + [k for k in prof["extra"] if k == "WhateverXe" or k.startswith("AMFIPass")] + INPUT_KEXTS + net
    # Lilu first, then WhateverXe must come after Lilu; ordering above keeps Lilu first.
    p["Kernel"]["Add"] = [kext_entry(k, True) for k in keys]
    # PS2's own VoodooInput is not shipped; VoodooI2C's copy serves both.
    p["Kernel"]["Block"] = []
    if prof["block_iondrv"]:
        p["Kernel"]["Block"] = [{
            "Arch": "Any", "Comment": "firmware framebuffer would steal display index 0 from NVRMFB (NullMoth, panel on dGPU)",
            "Enabled": True, "Identifier": "com.apple.iokit.IONDRVSupport", "MaxKernel": "", "MinKernel": "", "Strategy": "Exclude"}]
    p["Kernel"]["Emulate"].update(Cpuid1Data=hexb("55060A00000000000000000000000000"),
                                  Cpuid1Mask=hexb("FFFFFFFF000000000000000000000000"),
                                  DummyPowerManagement=False, MaxKernel="", MinKernel="")
    p["Kernel"]["Quirks"].update(
        AppleXcpmCfgLock=True, CustomSMBIOSGuid=not prof.get("minimal"), DisableIoMapper=True, DisableLinkeditJettison=True,
        PanicNoKextDump=True, PowerTimeoutKernelPanic=True, ProvideCurrentCpuInfo=True, XhciPortLimit=False)

    # Misc
    m = p["Misc"]
    m["Boot"].update(HibernateMode="None", HideAuxiliary=True, LauncherOption="Disabled", PickerAttributes=0x91,
                     PickerMode="External", PickerVariant="Acidanthera/GoldenGate", ShowPicker=True, TakeoffDelay=0,
                     Timeout=0, PollAppleHotKeys=False, ConsoleAttributes=0)
    m["Debug"].update(AppleDebug=True, ApplePanic=True, DisableWatchDog=True, DisplayDelay=0,
                      DisplayLevel=0x80000042, LogModules="*", SysReport=False, Target=0x41)
    m["Security"].update(AllowSetDefault=True, BlacklistAppleUpdate=True, DmgLoading="Signed", ExposeSensitiveData=7,
                         HaltLevel=0x80000000, ScanPolicy=SCAN_POLICY, SecureBootModel="Disabled", Vault="Optional",
                         AuthRestart=False, EnablePassword=False)
    m["BlessOverride"] = []
    tool = dict(m["Tools"][0]); tool.update(Enabled=False, Auxiliary=True, Comment="OpenCore UEFI shell: 'map -r' prints device paths (verify the Windows entry)", Name="OpenShell", Path="OpenShell.efi")
    m["Tools"] = [tool]
    if prof["nv"]:
        for nm, arg, cm in (("1401: Remove NVIDIA driver", "", "NullMoth: remove the NVIDIA driver at the next start"),
                            ("1401: Start once without NVIDIA driver", "once", "NullMoth: start macOS once without the NVIDIA driver")):
            m["Tools"].append(dict(tool, Name=nm, Path="NullMothSafe.efi", Arguments=arg, Comment=cm, Auxiliary=False,
                                   FullNvramAccess=True, TextMode=True, Flavour="Auto", Enabled=False))
    ent = dict(m["Entries"][0])
    ent.update(Arguments="", Auxiliary=False, Comment="Windows Boot Manager on disk 0 ESP (WD PC SN5000S). Windows keeps the native Lenovo SMBIOS (UpdateSMBIOSMode=Custom + CustomSMBIOSGuid).",
               Enabled=True, Flavour="Windows", Name="Windows", Path=WINDOWS_ESP, TextMode=False)
    m["Entries"] = [ent]

    # NVRAM
    ns = p["NVRAM"]["Add"]["7C436110-AB2A-4BBB-A880-FE41995C9F82"]
    ns.clear()
    ns.update({"boot-args": prof["boot"], "csr-active-config": hexb(prof["csr"]), "prev-lang:kbd": "en-US:0", "run-efi-updater": "No"})
    p["NVRAM"]["Delete"]["7C436110-AB2A-4BBB-A880-FE41995C9F82"] = ["boot-args", "csr-active-config"]
    rv = p["NVRAM"]["Add"]["4D1FDA02-38C7-4A6A-9CC6-4BCCA8B30102"]  # RestrictEvents: real CPU name instead of spoofed Comet Lake
    rv.clear(); rv.update({"revcpu": 1, "revcpuname": "12th Gen Intel(R) Core(TM) i5-12450HX", "revpatch": "cpuname"})
    p["NVRAM"]["Delete"]["4D1FDA02-38C7-4A6A-9CC6-4BCCA8B30102"] = ["revcpu", "revcpuname", "revpatch"]
    p["NVRAM"]["Add"]["4D1EDE05-38C7-4A6A-9CC6-4BCCA8B38C14"] = {"DefaultBackgroundColor": hexb("00000000")}
    p["NVRAM"]["Delete"]["4D1EDE05-38C7-4A6A-9CC6-4BCCA8B38C14"] = ["DefaultBackgroundColor"]
    p["NVRAM"]["WriteFlash"] = True

    # PlatformInfo (Mac identity only for macOS; Windows keeps Lenovo SMBIOS via Custom mode)
    pi = p["PlatformInfo"]
    pi.update(Automatic=True, CustomMemory=False, UpdateDataHub=True, UpdateNVRAM=True, UpdateSMBIOS=True,
              UpdateSMBIOSMode="Create" if prof.get("minimal") else "Custom", UseRawUuidEncoding=False)
    pi["Generic"].update(AdviseFeatures=False, MaxBIOSVersion=False, ProcessorType=0, SpoofVendor=True,
                         SystemMemoryStatus="Auto", SystemProductName=smbios["model"], SystemSerialNumber=smbios["serial"],
                         MLB=smbios["mlb"], SystemUUID=smbios["uuid"], ROM=bytes.fromhex(smbios["rom"]))

    # UEFI
    u = p["UEFI"]
    def drv(path, hide=False, args="", comment=""):
        return {"Arguments": args, "Comment": comment, "Enabled": True, "HideVerbose": hide, "LoadEarly": False, "Path": path}
    u["Drivers"] = [drv("HfsPlus.efi"), drv("OpenRuntime.efi"), drv("OpenCanopy.efi", True), drv("ResetNvramEntry.efi", args="--preserve-boot", comment="Reset NVRAM picker entry; --preserve-boot keeps firmware boot options (Windows Boot Manager) intact")]
    u["ConnectDrivers"] = True
    u["Quirks"].update(ReleaseUsbOwnership=True, RequestBootVarRouting=True, ResizeGpuBars=-1, UnblockFsConnect=False)
    u["Output"].update(ConsoleMode="", Resolution="Max", ProvideConsoleGop=True, TextRenderer="BuiltinGraphics",
                       DirectGopRendering=False, GopBurstMode=False, UIScale=0)
    u["APFS"].update(EnableJumpstart=True, GlobalConnect=False, HideVerbose=False, JumpstartHotPlug=False, MinDate=-1, MinVersion=-1)
    u["ReservedMemory"] = []
    return p


def main():
    smb = json.load(open(os.path.join(ROOT, "private_smbios.json")))
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    for d in ("BOOT", "OC/ACPI", "OC/Drivers", "OC/Kexts", "OC/Resources", "OC/Tools"):
        os.makedirs(os.path.join(OUT, d))
    # OpenCore DEBUG binaries
    shutil.copy(f"{OC}/X64/EFI/BOOT/BOOTx64.efi", f"{OUT}/BOOT/BOOTx64.efi")
    shutil.copy(f"{OC}/X64/EFI/OC/OpenCore.efi", f"{OUT}/OC/OpenCore.efi")
    for d in ("OpenRuntime.efi", "OpenCanopy.efi", "ResetNvramEntry.efi"):
        shutil.copy(f"{OC}/X64/EFI/OC/Drivers/{d}", f"{OUT}/OC/Drivers/{d}")
    shutil.copy(f"{BIN}/Drivers/HfsPlus.efi", f"{OUT}/OC/Drivers/HfsPlus.efi")
    shutil.copy(f"{OC}/X64/EFI/OC/Tools/OpenShell.efi", f"{OUT}/OC/Tools/OpenShell.efi")
    shutil.copy(f"{ROOT}/refs/1401-added/Tools/NullMothSafe.efi", f"{OUT}/OC/Tools/NullMothSafe.efi")
    # GoldenGate resources (same OcBinaryData snapshot: Font, Label, Image/Acidanthera/GoldenGate)
    R = f"{OUT}/OC/Resources"
    shutil.copytree(f"{BIN}/Resources/Font", f"{R}/Font")
    shutil.copytree(f"{BIN}/Resources/Label", f"{R}/Label")
    os.makedirs(f"{R}/Image/Acidanthera")
    shutil.copytree(f"{BIN}/Resources/Image/Acidanthera/GoldenGate", f"{R}/Image/Acidanthera/GoldenGate")
    # GoldenGate ships no Apple logo; add the macOS icons from the chris1111 Flavours-AppleSet theme (same ic07/ic13 icns format)
    for ic in ("Apple.icns", "Apple15.icns"):
        shutil.copy(f"{ROOT}/refs/apple-icons/{ic}", f"{R}/Image/Acidanthera/GoldenGate/{ic}")
    # ACPI
    for f in ("SSDT-EC-USBX", "SSDT-PLUG", "SSDT-RTCAWAC", "SSDT-GPRW", "SSDT-XOSI", "SSDT-PNLF"):
        shutil.copy(f"{ACPI_OUT}/{f}.aml", f"{OUT}/OC/ACPI/{f}.aml")
    # Kexts
    for key in ALL_KEXTS:
        k = K[key]
        if k["src"] is None:
            continue
        dst = f"{OUT}/OC/Kexts/{k['name']}"
        shutil.copytree(k["src"], dst)
    # official VoodooI2C 2.9.1 does not match the Alder Lake-S LPSS I2C controller 8086:7ACC (touchpad host): add it to the
    # Ice Lake-class personality (the reference EFI's newer build does the same). Binary untouched, Info.plist only.
    ip = f"{OUT}/OC/Kexts/VoodooI2C.kext/Contents/Info.plist"
    vi = plistlib.load(open(ip, "rb"))
    pers = vi["IOKitPersonalities"]["VoodooI2CPCILakeController"]
    if "0x7acc8086" not in pers["IOPCIMatch"]:
        pers["IOPCIMatch"] += " 0x7acc8086&0xFFFCFFFF"
    plistlib.dump(vi, open(ip, "wb"))
    # trim unused VoodooPS2 plugins (no PS/2 mouse/trackpad on this laptop) - keep Keyboard only
    pl = f"{OUT}/OC/Kexts/VoodooPS2Controller.kext/Contents/PlugIns"
    for d in ("VoodooPS2Mouse.kext", "VoodooPS2Trackpad.kext", "VoodooInput.kext"):
        shutil.rmtree(f"{pl}/{d}", ignore_errors=True)
    # configs
    os.makedirs(PROFILES, exist_ok=True)
    for f in os.listdir(PROFILES):
        os.remove(os.path.join(PROFILES, f))
    for name, prof in PROFILES_DEF.items():
        cfg = build_config(name, prof, smb)
        with open(os.path.join(PROFILES, f"config-{name}.plist"), "wb") as fh:
            plistlib.dump(cfg, fh, sort_keys=False)
    shutil.copy(os.path.join(PROFILES, "config-A-install-safe.plist"), f"{OUT}/OC/config.plist")
    print("built", OUT)


if __name__ == "__main__":
    main()
