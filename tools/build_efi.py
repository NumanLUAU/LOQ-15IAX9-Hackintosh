def kext_entry(key, enabled):
    k = K[key]
    p = os.path.join(OUT, "OC", "Kexts", k["name"])
    info = plistlib.load(open(os.path.join(p, "Contents", "Info.plist"), "rb"))
    exe = info.get("CFBundleExecutable")
    return {
        "Arch": "Any", "BundlePath": k["name"], "Comment": k["comment"], "Enabled": enabled,
        "ExecutablePath": f"Contents/MacOS/{exe}" if exe else "", "MaxKernel": k["max"],
        "MinKernel": k["min"], "PlistPath": "Contents/Info.plist",
    }


def hexb(s):
    return bytes.fromhex(s.replace(" ", ""))


def acpi_add(name, enabled=True):
    return {"Comment": name, "Enabled": enabled, "Path": name}


